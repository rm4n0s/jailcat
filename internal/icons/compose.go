// TagIconSourceUnsupported is the tag of the error [BadgeIcon] returns for an icon it cannot
// use as the source of a build's icon: an XPM (or any other format that is not SVG or PNG), an
// SVG that is not well-formed or has no size or has an internal DTD subset, a PNG that cannot
// be read, or a file that is too large. The caller falls back to [RandomIcon] (SPEC §10.2).
const TagIconSourceUnsupported = "IconSourceUnsupported"

// TagBadgeCanceled is the tag of the error [BadgeIcon] returns when its ctx is done.
const TagBadgeCanceled = "BadgeCanceled"

const (
	tagIconSourceUnsupported = TagIconSourceUnsupported
	tagBadgeCanceled         = TagBadgeCanceled
	tagIconReadFailed        = "IconReadFailed"
)

// The limits of a source icon: larger files and images are refused.
const (
	maxSourceBytes = 4 << 20
	maxPNGSide     = 4096
)

// The canvas of a build's icon and where the badge sits on it (SPEC §10.2): the badge is 40% of
// the canvas wide and touches its bottom-right corner.
const (
	canvasSize = "128"
	badgeSize  = "51.2"
	badgeAt    = "76.8"
)

// badgePrefix is the id prefix of the badge. The prefix of a source starts with "s" and
// RandomIcon's ids with "jcr-", so no id of the three can be another's.
const badgePrefix = "jcb-"

// generatedHeader is written at the top of every icon, after the XML declaration, so Jailcat
// can tell its own icons from other files (SPEC §9.5).
const generatedHeader = "<!-- Generated by Jailcat. Do not edit: change it in Jailcat and rebuild. -->"

// BadgeIcon returns the SVG icon of a build made from the icon src (as [Lookup] found it): a
// 128x128 canvas with the source drawn over all of it and the badge of assets/badge.svg in
// the bottom-right corner, 40% of the canvas wide (SPEC §10.2). The result renders in librsvg
// and in Qt SVG, is the same for the same source, and ends with a newline.
//
// An SVG source is read with encoding/xml, sanitized and inlined as a nested <svg>; the
// comment of parseSVG lists what is removed. The rules of a source's <style> element are applied
// only when they are the colour-scheme pattern of KDE's icons (".class { fill: #rrggbb }": see
// parseStyleRules); any other <style> is lost, so an icon that depends on it may look different.
// A PNG source is embedded as a base64 data:
// URI in an <image>.
//
// A source that cannot be used (see [TagIconSourceUnsupported]) is not a failure of the build:
// the caller makes a [RandomIcon] instead. A done ctx gives [TagBadgeCanceled].
func BadgeIcon(ctx context.Context, src Icon) ([]byte, error) {
	if err := ctx.Err(); err != nil {
		return nil, errors.NewErr(tagBadgeCanceled, err)
	}
	var content *node
	switch src.Format {
	case FormatSVG:
		data, err := readSource(src.Path)
		if err != nil {
			return nil, err
		}
		sum := sha256.Sum256(data)
		prefix := "s" + hex.EncodeToString(sum[:4]) + "-"
		svg, err := parseSVG(data, prefix)
		if err != nil {
			return nil, err
		}
		content = svg.nested("0", "0", canvasSize, canvasSize)
	case FormatPNG:
		data, err := readSource(src.Path)
		if err != nil {
			return nil, err
		}
		cfg, err := png.DecodeConfig(bytes.NewReader(data))
		if err != nil {
			return nil, errors.NewErr(tagIconSourceUnsupported, err).SetMetadata("reason", "not a PNG", "path", src.Path)
		}
		if cfg.Width <= 0 || cfg.Height <= 0 || cfg.Width > maxPNGSide || cfg.Height > maxPNGSide {
			return nil, errors.New(tagIconSourceUnsupported, "the PNG has an unusable size", "reason", "PNG size", "path", src.Path, "width", cfg.Width, "height", cfg.Height)
		}
		w, h := strconv.Itoa(cfg.Width), strconv.Itoa(cfg.Height)
		content = element("svg", "x", "0", "y", "0", "width", canvasSize, "height", canvasSize, "viewBox", "0 0 "+w+" "+h).add(
			element("image", "width", w, "height", h,
				"xlink:href", "data:image/png;base64,"+base64.StdEncoding.EncodeToString(data)))
	default:
		return nil, errors.New(tagIconSourceUnsupported, "Jailcat cannot draw this icon format", "reason", "format", "format", string(src.Format), "path", src.Path)
	}

	badge, err := badgeNode()
	if err != nil {
		return nil, err
	}
	return document(content, badge), nil
}

// readSource reads an icon file of at most maxSourceBytes; a larger file is refused.
func readSource(path string) ([]byte, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, errors.NewErr(tagIconReadFailed, err).SetMetadata("path", path)
	}
	defer func() { _ = f.Close() }()
	data, err := io.ReadAll(io.LimitReader(f, maxSourceBytes+1))
	if err != nil {
		return nil, errors.NewErr(tagIconReadFailed, err).SetMetadata("path", path)
	}
	if len(data) > maxSourceBytes {
		return nil, errors.New(tagIconSourceUnsupported, "the icon file is too large", "reason", "too large", "path", path, "max", maxSourceBytes)
	}
	return data, nil
}

// badgeNode returns the badge as a nested <svg> in the bottom-right corner of the canvas.
func badgeNode() (*node, error) {
	badge, err := parseSVG(assets.Badge(), badgePrefix)
	if err != nil {
		return nil, err
	}
	return badge.nested(badgeAt, badgeAt, badgeSize, badgeSize), nil
}

// document writes the icon: the 128x128 canvas holding the content nodes and the badge.
func document(content, badge *node) []byte {
	root := element("svg",
		"xmlns", nsSVG, "xmlns:xlink", nsXLink,
		"width", canvasSize, "height", canvasSize, "viewBox", "0 0 "+canvasSize+" "+canvasSize)
	root.add(content)
	if badge != nil {
		root.add(badge)
	}
	var b strings.Builder
	b.WriteString("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n")
	b.WriteString(generatedHeader)
	b.WriteByte('\n')
	root.write(&b, 0, false)
	return []byte(b.String())
}

// palette is the pairs of colours of a random icon's gradient (top-left, bottom-right). Every
// colour has a contrast ratio of at least 4.5 with the white letter (WCAG AA).
var palette = [8][2]string{
	{"#2563eb", "#1e3a8a"}, // blue
	{"#7c3aed", "#4c1d95"}, // violet
	{"#a21caf", "#701a75"}, // magenta
	{"#dc2626", "#991b1b"}, // red
	{"#c2410c", "#7c2d12"}, // orange
	{"#15803d", "#14532d"}, // green
	{"#0f766e", "#134e4a"}, // teal
	{"#0e7490", "#164e63"}, // cyan
}

// gradientDirections are the (x1, y1, x2, y2) of the random icon's gradient.
var gradientDirections = [4][4]string{
	{"0", "0", "1", "1"}, {"1", "0", "0", "1"}, {"0", "0", "0", "1"}, {"0", "0", "1", "0"},
}

// RandomIcon returns the SVG icon of a build that has no usable app icon (SPEC §10.3): a 128x128
// canvas with a background shape (a circle, a rounded square or a hexagon) filled with a
// gradient of two colours from a fixed palette, the first letter of name in white, and the
// badge in the bottom-right corner. The shape, the colours and the gradient's direction come
// from seed only, the letter from name only, so the same seed and name always give the same
// bytes (the algorithm is the PCG of math/rand/v2, which is fixed). An empty name, or one that
// does not start with a printable character, gives "?". Leading white space of name is skipped.
//
// The result ends with a newline.
func RandomIcon(seed int64, name string) []byte {
	// One 64-bit draw is split into the choices; Rand's own methods are not used, because only
	// the generator's output is promised never to change.
	v := rand.NewPCG(uint64(seed), 0x6a61696c63617421).Uint64()
	colours := palette[v%uint64(len(palette))]
	shape := (v >> 8) % 3
	dir := gradientDirections[(v>>16)%uint64(len(gradientDirections))]

	gradient := element("linearGradient", "id", "jcr-background", "x1", dir[0], "y1", dir[1], "x2", dir[2], "y2", dir[3]).add(
		element("stop", "offset", "0", "stop-color", colours[0]),
		element("stop", "offset", "1", "stop-color", colours[1]),
	)
	fill := "url(#jcr-background)"
	var background *node
	switch shape {
	case 0:
		background = element("circle", "cx", "64", "cy", "64", "r", "60", "fill", fill)
	case 1:
		background = element("rect", "x", "6", "y", "6", "width", "116", "height", "116", "rx", "28", "fill", fill)
	default:
		background = element("polygon", "points", "64,4 116,34 116,94 64,124 12,94 12,34",
			"fill", fill, "stroke", colours[1], "stroke-width", "4", "stroke-linejoin", "round")
	}
	letter := element("text", "x", "62", "y", "76", "text-anchor", "middle",
		"font-family", "sans-serif", "font-size", "64", "font-weight", "bold", "fill", "#ffffff").
		add(&node{text: initial(name)})

	content := element("g").add(
		element("defs").add(gradient),
		background,
		letter,
	)
	badge, err := badgeNode()
	if err != nil {
		// The badge is an embedded file that a test reads, so this does not happen; the icon
		// is still better without a badge than not made at all.
		badge = nil
	}
	return document(content, badge)
}

// initial returns the first letter of name in upper case, or "?".
func initial(name string) string {
	r, size := utf8.DecodeRuneInString(strings.TrimSpace(name))
	if size == 0 || r == utf8.RuneError || !unicode.IsPrint(r) {
		return "?"
	}
	return string(unicode.ToUpper(r))
}
