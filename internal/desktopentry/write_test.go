func TestWriteBuiltEntryGolden(t *testing.T) {
	want, err := os.ReadFile(filepath.Join("testdata", "built-entry.golden"))
	if err != nil {
		t.Fatal(err)
	}
	e := buildGolden(t)
	got := mustWrite(t, e)
	if got != string(want) {
		t.Fatalf("written entry differs from testdata/built-entry.golden:\n%s\n--- want ---\n%s", got, want)
	}

	// The golden text reads back as what was put in.
	back := mustParse(t, got)
	main := back.Main()
	checks := map[string]string{
		"Comment": "Code Editing.\nRedefined. C:\\temp", "Path": " spaced ", "Name[de]": "Visual Studio Code (abgeschirmt)",
	}
	for key, want := range checks {
		if got := main.String(key); got != want {
			t.Errorf("String(%q) = %q, want %q", key, got, want)
		}
	}
	if kw := main.Strings("Keywords"); !reflect.DeepEqual(kw, []string{"vscode", "a;b", "Café"}) {
		t.Errorf("Keywords = %q", kw)
	}
	if b, err := main.Bool("Terminal"); err != nil || b {
		t.Errorf("Terminal = %v, %v", b, err)
	}
	args, err := SplitExec(main.String("Exec"))
	want2 := []string{"/home/u/My Bin/firejail-code", "--title", `a "quoted" $x \ 100%`, "%F"}
	if err != nil || !reflect.DeepEqual(args, want2) {
		t.Errorf("Exec args = %q, %v", args, err)
	}
	if ids := back.Actions(); len(ids) != 1 || ids[0].String("Name") != "New Empty Window" {
		t.Errorf("Actions() = %v", ids)
	}
	if !reflect.DeepEqual(e, back) {
		t.Error("the built entry and the parsed golden text differ")
	}
}

func TestSetRoundTrip(t *testing.T) {
	values := []string{
		"", "plain", " leading", "trailing ", "  both  ", "   ", "a\nb", "a\r\nb", "\n", "tab\there", `back\slash`,
		`\n is text`, `\\`, `\`, "semi;colon", "Café 日本語", "emoji 😀", "a=b", "[brackets]", "#hash", "100%", "\t lead tab",
		"Exec=injected", "x\n[Injected Group]\ny=z",
	}
	for _, v := range values {
		e := NewEntry()
		g := e.Group(MainGroup)
		if err := g.Set("K", v); err != nil {
			t.Fatalf("Set(%q): %v", v, err)
		}
		if err := g.SetLocale("K", "de_DE@euro", v); err != nil {
			t.Fatalf("SetLocale(%q): %v", v, err)
		}
		text := mustWrite(t, e)
		back := mustParse(t, text)
		if got := back.Main().String("K"); got != v {
			t.Errorf("String after round trip: %q became %q (file %q)", v, got, text)
		}
		if got := back.Main().LocaleString("K", "de_DE.UTF-8@euro"); got != v {
			t.Errorf("LocaleString after round trip: %q became %q", v, got)
		}
		if len(back.Groups()) != 1 || len(back.Main().Keys()) != 2 {
			t.Errorf("value %q injected structure into the file: %q", v, text)
		}
		items := []string{v, "x", v}
		if err := g.SetStrings("L", items); err != nil {
			t.Fatalf("SetStrings(%q): %v", items, err)
		}
		if got := mustParse(t, mustWrite(t, e)).Main().Strings("L"); !reflect.DeepEqual(got, items) {
			t.Errorf("Strings after round trip: %q became %q", items, got)
		}
	}
}

func TestSetRefusals(t *testing.T) {
	long := strings.Repeat("a", 3)
	tests := []struct {
		name  string
		do    func(g *Group) error
		route string
	}{
		{"Set empty key", func(g *Group) error { return g.Set("", "v") }, "Group.Set->Group.setRaw.InvalidKeyName"},
		{"Set key with a space", func(g *Group) error { return g.Set("Na me", "v") }, "Group.Set->Group.setRaw.InvalidKeyName"},
		{"Set key with an equals sign", func(g *Group) error { return g.Set("a=b", "v") }, "Group.Set->Group.setRaw.InvalidKeyName"},
		{"Set key with an underscore", func(g *Group) error { return g.Set("a_b", "v") }, "Group.Set->Group.setRaw.InvalidKeyName"},
		{"Set key with a dot", func(g *Group) error { return g.Set("a.b", "v") }, "Group.Set->Group.setRaw.InvalidKeyName"},
		{"Set key with a line break", func(g *Group) error { return g.Set("a\nb", "v") }, "Group.Set->Group.setRaw.InvalidKeyName"},
		{"Set key with non-ASCII", func(g *Group) error { return g.Set("Näme", "v") }, "Group.Set->Group.setRaw.InvalidKeyName"},
		{"Set key with a locale postfix", func(g *Group) error { return g.Set("Name[de]", "v") }, "Group.Set->Group.setRaw.InvalidKeyName"},
		{"Set value with a NUL", func(g *Group) error { return g.Set("Name", "a\x00b") }, "Group.Set->Group.setRaw.InvalidValue"},
		{"Set value with invalid UTF-8", func(g *Group) error { return g.Set("Name", "a\xffb") }, "Group.Set->Group.setRaw.InvalidValue"},
		{"SetLocale bad key", func(g *Group) error { return g.SetLocale("Na me", "de", "v") }, "Group.SetLocale->Group.setRaw.InvalidKeyName"},
		{"SetLocale NUL value", func(g *Group) error { return g.SetLocale("Name", "de", "\x00") }, "Group.SetLocale->Group.setRaw.InvalidValue"},
		{"SetLocale empty locale", func(g *Group) error { return g.SetLocale("Name", "", "v") }, "Group.SetLocale.InvalidLocale"},
		{"SetLocale locale with a bracket", func(g *Group) error { return g.SetLocale("Name", "de]", "v") }, "Group.SetLocale.InvalidLocale"},
		{"SetLocale locale with a line break", func(g *Group) error { return g.SetLocale("Name", "de\n", "v") }, "Group.SetLocale.InvalidLocale"},
		{"SetLocale locale with a space", func(g *Group) error { return g.SetLocale("Name", "d e", "v") }, "Group.SetLocale.InvalidLocale"},
		{"SetStrings bad key", func(g *Group) error { return g.SetStrings("Key s", []string{"a"}) }, "Group.SetStrings->Group.setRaw.InvalidKeyName"},
		{"SetStrings NUL item", func(g *Group) error { return g.SetStrings("Keywords", []string{"a", "b\x00"}) }, "Group.SetStrings->Group.setRaw.InvalidValue"},
		{"SetBool bad key", func(g *Group) error { return g.SetBool("Key s", true) }, "Group.SetBool->Group.setRaw.InvalidKeyName"},
		{"Comment with a NUL", func(g *Group) error { return g.Comment("a\x00b") }, "Group.Comment->commentLines.InvalidComment"},
		{"Comment with a carriage return", func(g *Group) error { return g.Comment("a\rb") }, "Group.Comment->commentLines.InvalidComment"},
		{"Comment with invalid UTF-8", func(g *Group) error { return g.Comment(long + "\xff") }, "Group.Comment->commentLines.InvalidComment"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			e := NewEntry()
			g := e.Group(MainGroup)
			err := tt.do(g)
			if err == nil {
				t.Fatal("expected an error")
			}
			checkRoute(t, err, tt.route)
			if got := mustWrite(t, e); got != "[Desktop Entry]\n" {
				t.Errorf("a refused call changed the entry: %q", got)
			}
		})
	}

	err := NewEntry().Comment("a\x00")
	if err == nil {
		t.Fatal("expected an error")
	}
	checkRoute(t, err, "Entry.Comment->commentLines.InvalidComment")
}

