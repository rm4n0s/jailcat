func TestSetOrder(t *testing.T) {
	e := mustParse(t, "# top\n[A]\nz=1\ny=2\n\n[B]\nx=3\n")
	a := e.Lookup("A")
	steps := []func() error{
		func() error { return a.Set("y", "two") },      // replaced in place
		func() error { return a.Set("new", "n") },      // after the last key, before the blank line
		func() error { return a.Comment("a comment") }, // after that
		func() error { return e.Group("B").Set("w", "4") },
		func() error { return e.Group("C").Set("v", "5") }, // a new group after B, separated by a blank line
		func() error { return a.Set("z", "one") },
	}
	for i, step := range steps {
		if err := step(); err != nil {
			t.Fatalf("step %d: %v", i, err)
		}
	}
	want := "# top\n[A]\nz=one\ny=two\nnew=n\n# a comment\n\n[B]\nx=3\nw=4\n\n[C]\nv=5\n"
	if got := mustWrite(t, e); got != want {
		t.Errorf("got:\n%s\nwant:\n%s", got, want)
	}
	if got, want := groupNames(e), []string{"A", "B", "C"}; !reflect.DeepEqual(got, want) {
		t.Errorf("groups = %q, want %q", got, want)
	}
}

