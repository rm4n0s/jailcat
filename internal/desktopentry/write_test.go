	t.Helper()
	exec, err := JoinExec([]string{"/home/u/My Bin/firejail-code", "--title", `a "quoted" $x \ 100%`}, "%F")
	if err != nil {
		t.Fatal(err)
	}
	action, err := JoinExec([]string{"/home/u/My Bin/firejail-code", "--new-window"}, "%F")
	if err != nil {
		t.Fatal(err)
	}
	e := NewEntry()
	main := e.Group(MainGroup)
	for _, c := range []string{"Generated by Jailcat. Do not edit: change it in Jailcat and rebuild.", "jailcat-build: 7"} {
		if err := main.Comment(c); err != nil {
			t.Fatal(err)
		}
	}
	steps := []func() error{
		func() error { return main.Set("Type", "Application") },
		func() error { return main.Set("Name", "Visual Studio Code (sandboxed)") },
		func() error { return main.SetLocale("Name", "de", "Visual Studio Code (abgeschirmt)") },
		func() error { return main.Set("Comment", "Code Editing.\nRedefined. C:\\temp") },
		func() error { return main.Set("Exec", exec) },
		func() error { return main.Set("Icon", "firejail-code") },
		func() error { return main.SetStrings("Keywords", []string{"vscode", "a;b", "Café"}) },
		func() error { return main.SetBool("Terminal", false) },
		func() error { return main.Set("Path", " spaced ") },
		func() error { return main.SetStrings("Actions", []string{"new-empty-window"}) },
		func() error { return main.Set("X-Jailcat-Build", "7") },
		func() error {
			return e.Group(ActionGroupPrefix+"new-empty-window").Set("Name", "New Empty Window")
		},
		func() error { return e.Group(ActionGroupPrefix+"new-empty-window").Set("Exec", action) },
	}
	for i, step := range steps {
		if err := step(); err != nil {
			t.Fatalf("step %d: %v", i, err)
		}
	}
	return e
