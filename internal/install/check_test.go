// privateHome2 makes the settings of the VS Code-like build on the kit's scratch home.
func privateHome2(k *kit) func(s *firejail.Settings) {
	return vscodeBuild(k.dirs.Homes)
}

func TestCheckConflictKinds(t *testing.T) {
	const foreignText = "echo mine\n"
	jailcatHeader := func(first string) string { return first + firejail.HeaderLine + "\n# jailcat-build: 99\nrest\n" }
	tests := []struct {
		name string
		kind Kind
		// setup puts something at the target and returns the owner records.
		setup func(t *testing.T, f File) map[string]record
		want  ConflictKind
		owner int64
		over  bool
		none  bool
	}{
		{"missing", KindLauncher, func(t *testing.T, f File) map[string]record { return nil }, "", 0, false, true},
		{"ours and unchanged", KindLauncher, func(t *testing.T, f File) map[string]record {
			writeText(t, f.Path, "old launcher\n")
			return map[string]record{f.Path: {7, sumOf("old launcher\n")}}
		}, "", 0, false, true},
		{"ours but edited", KindLauncher, func(t *testing.T, f File) map[string]record {
			writeText(t, f.Path, jailcatHeader("#!/bin/sh\n# edited\n"))
			return map[string]record{f.Path: {7, sumOf("old launcher\n")}}
		}, ConflictEdited, 7, true, false},
		{"ours, edited, header gone", KindLauncher, func(t *testing.T, f File) map[string]record {
			writeText(t, f.Path, foreignText)
			return map[string]record{f.Path: {7, sumOf("old launcher\n")}}
		}, ConflictEdited, 7, false, false},
		{"another build's", KindProfile, func(t *testing.T, f File) map[string]record {
			writeText(t, f.Path, jailcatHeader(""))
			return map[string]record{f.Path: {4, sumOf(jailcatHeader(""))}}
		}, ConflictOtherBuild, 4, false, false},
		{"Jailcat's header, not recorded (launcher)", KindLauncher, func(t *testing.T, f File) map[string]record {
			writeText(t, f.Path, jailcatHeader("#!/bin/sh\n"))
			return nil
		}, ConflictForeignJailcat, 0, true, false},
		{"Jailcat's header, not recorded (profile)", KindProfile, func(t *testing.T, f File) map[string]record {
			writeText(t, f.Path, jailcatHeader(""))
			return nil
		}, ConflictForeignJailcat, 0, true, false},
		{"Jailcat's header, not recorded (desktop entry)", KindDesktop, func(t *testing.T, f File) map[string]record {
			writeText(t, f.Path, "[Desktop Entry]\n"+firejail.HeaderLine+"\n# jailcat-build: 1\nName=x\n")
			return nil
		}, ConflictForeignJailcat, 0, true, false},
		{"Jailcat's header, not recorded (icon)", KindIcon, func(t *testing.T, f File) map[string]record {
			writeText(t, f.Path, "<?xml version=\"1.0\"?>\n<!-- Generated by Jailcat. Do not edit: change it in Jailcat and rebuild. -->\n<svg/>\n")
			return nil
		}, ConflictForeignJailcat, 0, true, false},
		{"a profile's header is not an icon's", KindIcon, func(t *testing.T, f File) map[string]record {
			writeText(t, f.Path, jailcatHeader(""))
			return nil
		}, ConflictForeign, 0, false, false},
		{"header too far down", KindLauncher, func(t *testing.T, f File) map[string]record {
			writeText(t, f.Path, "#!/bin/sh\n\n\n\n\n\n\n"+firejail.HeaderLine+"\n")
			return nil
		}, ConflictForeign, 0, false, false},
		{"foreign file", KindDesktop, func(t *testing.T, f File) map[string]record {
			writeText(t, f.Path, "[Desktop Entry]\nName=Mine\n")
			return nil
		}, ConflictForeign, 0, false, false},
		{"empty foreign file", KindProfile, func(t *testing.T, f File) map[string]record {
			writeText(t, f.Path, "")
			return nil
		}, ConflictForeign, 0, false, false},
		{"a folder in the place", KindLauncher, func(t *testing.T, f File) map[string]record {
			if err := os.MkdirAll(f.Path, 0o755); err != nil {
				t.Fatal(err)
			}
			return nil
		}, ConflictForeign, 0, false, false},
		{"a symlink in the place", KindProfile, func(t *testing.T, f File) map[string]record {
			target := filepath.Join(t.TempDir(), "elsewhere")
			writeText(t, target, jailcatHeader(""))
			if err := os.MkdirAll(filepath.Dir(f.Path), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.Symlink(target, f.Path); err != nil {
				t.Fatal(err)
			}
			return nil
		}, ConflictForeign, 0, false, false},
		{"a folder in the place of another build's file", KindIcon, func(t *testing.T, f File) map[string]record {
			if err := os.MkdirAll(f.Path, 0o755); err != nil {
				t.Fatal(err)
			}
			return map[string]record{f.Path: {5, ""}}
		}, ConflictOtherBuild, 5, false, false},
		{"home exists", KindHome, func(t *testing.T, f File) map[string]record {
			if err := os.MkdirAll(filepath.Join(f.Path, "data"), 0o700); err != nil {
				t.Fatal(err)
			}
			return nil
		}, "", 0, false, true},
		{"a file in the place of the home", KindHome, func(t *testing.T, f File) map[string]record {
			writeText(t, f.Path, "x")
			return nil
		}, ConflictForeign, 0, false, false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			k := newKit(t)
			p := k.prepare(privateHome2(k))
			f := file(t, p, tt.kind)
			records := tt.setup(t, f)
			got, err := Check(context.Background(), p, owners(records))
			if err != nil {
				t.Fatal(err)
			}
			if tt.none {
				if len(got) != 0 {
					t.Fatalf("conflicts = %+v, want none", got)
				}
				return
			}
			if len(got) != 1 {
				t.Fatalf("conflicts = %+v, want one", got)
			}
			c := got[0]
			if c.File.Path != f.Path || c.Kind != tt.want || c.Owner != tt.owner || c.Overwritable != tt.over {
				t.Errorf("conflict = {%s %s owner %d overwritable %v}, want {%s %s owner %d overwritable %v}",
					c.File.Path, c.Kind, c.Owner, c.Overwritable, f.Path, tt.want, tt.owner, tt.over)
			}
		})
	}
}

func TestCheckListsEveryConflictInOrder(t *testing.T) {
	k := newKit(t)
	p := k.prepare(nil)
	for _, kind := range []Kind{KindDesktop, KindProfile} {
		writeText(t, file(t, p, kind).Path, "mine\n")
	}
	got, err := Check(context.Background(), p, nil)
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 2 || got[0].File.Kind != KindProfile || got[1].File.Kind != KindDesktop {
		t.Errorf("conflicts = %+v", got)
	}
}

func TestCheckLargeFileKeepsItsHash(t *testing.T) {
	// A file longer than the header scan still hashes whole.
	k := newKit(t)
	p := k.prepare(nil)
	f := file(t, p, KindProfile)
	text := firejail.HeaderLine + "\n" + strings.Repeat("x", 10000) + "\n"
	writeText(t, f.Path, text)
	got, err := Check(context.Background(), p, owners(map[string]record{f.Path: {7, sumOf(text)}}))
	if err != nil || len(got) != 0 {
		t.Errorf("Check = %+v, %v; want no conflict", got, err)
	}
	got, err = Check(context.Background(), p, owners(map[string]record{f.Path: {7, sumOf(text + "y")}}))
	if err != nil || len(got) != 1 || got[0].Kind != ConflictEdited {
		t.Errorf("Check = %+v, %v; want an edited conflict", got, err)
	}
}

func TestCheckRoutes(t *testing.T) {
	t.Run("canceled", func(t *testing.T) {
		k := newKit(t)
		ctx, cancel := context.WithCancel(context.Background())
		cancel()
		_, err := Check(ctx, k.prepare(nil), nil)
		requireRoute(t, err, tagCheckCanceled, "Check."+tagCheckCanceled)
	})
	t.Run("owner fails with a plain error", func(t *testing.T) {
		k := newKit(t)
		p := k.prepare(nil)
		writeText(t, file(t, p, KindProfile).Path, "mine\n")
		_, err := Check(context.Background(), p, func(string) (int64, string, bool, error) {
			return 0, "", false, os.ErrDeadlineExceeded
		})
		requireRoute(t, err, tagOwnerLookupFailed, "Check->checkFile."+tagOwnerLookupFailed)
	})
	t.Run("owner fails with a tagged error", func(t *testing.T) {
		k := newKit(t)
		p := k.prepare(nil)
		writeText(t, file(t, p, KindProfile).Path, "mine\n")
		_, err := Check(context.Background(), p, func(string) (int64, string, bool, error) {
			return 0, "", false, errors.New("DatabaseGone", "the database is gone")
		})
		if appErr, ok := errors.FromError(err); !ok || appErr.Tag != "DatabaseGone" {
			t.Errorf("err = %v, want the caller's own tagged error untouched", err)
		}
	})
	t.Run("a parent that is a file", func(t *testing.T) {
		k := newKit(t)
		p := k.prepare(nil)
		f := file(t, p, KindProfile)
		// The profiles folder is a file, so the target cannot be looked at.
		writeText(t, filepath.Dir(f.Path), "not a folder")
		_, err := Check(context.Background(), p, nil)
		requireRoute(t, err, tagTargetStatFailed, "Check->checkFile."+tagTargetStatFailed)
	})
	t.Run("unreadable file", func(t *testing.T) {
		k := newKit(t)
		p := k.prepare(nil)
		f := file(t, p, KindProfile)
		writeText(t, f.Path, "mine\n")
		if err := os.Chmod(f.Path, 0); err != nil {
			t.Fatal(err)
		}
		if _, err := os.ReadFile(f.Path); err == nil {
			t.Skip("the test runs as a user that reads files without permission")
		}
		_, err := Check(context.Background(), p, nil)
		requireRoute(t, err, tagTargetReadFailed, "Check->checkFile."+tagTargetReadFailed)
	})
}
